export type MessageKey = keyof typeof messages['zh-CN']

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  const language = (navigator.languages?.[0] || navigator.language).toLowerCase()
  return language.startsWith('zh') || language === 'zh-tw' || language === 'zh-hk' ? 'zh-CN' : 'en'
}

export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}) {
  let value: string = messages[locale][key]
  return value.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}
